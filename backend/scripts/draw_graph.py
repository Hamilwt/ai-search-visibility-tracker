"""Render the extraction graph to docs/langgraph_architecture.md.

Run from the backend directory:
    python scripts/draw_graph.py

Building the graph needs no provider calls and no network.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app.agents.extraction_graph import MAX_ATTEMPTS, build_extraction_graph  # noqa: E402
from app.llm.base import BaseLLMProvider, LLMResult  # noqa: E402


class UnusedProvider(BaseLLMProvider):
    async def generate(self, prompt: str) -> LLMResult:
        raise AssertionError("drawing the graph must not call the provider")


def main() -> None:
    diagram = build_extraction_graph(UnusedProvider()).get_graph().draw_mermaid()
    doc = f"""# Extraction reflection graph

Generated by `backend/scripts/draw_graph.py`. Do not hand-edit the diagram.

```mermaid
{diagram}```

## Nodes

- `extract`: one LLM call with the extraction template (attempt +1).
- `validate`: strict `_parse` (fence-strip, JSON, Pydantic, server-side
  `is_target_brand`/domains). Success stores `result`; failure stores the
  `validation_error` string.
- `fix`: one LLM call with the repair template built from the last output
  plus its validation error (attempt +1).

## Edges

- `extract` → `validate` always.
- `validate` → END when `result` is set (success).
- `validate` → END when `attempts >= {MAX_ATTEMPTS}` (budget exhausted,
  degrades to `failed_extraction`).
- Otherwise `validate` → `fix` → `validate` (critique loop).
"""
    out = os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        "..",
        "docs",
        "langgraph_architecture.md",
    )
    with open(os.path.normpath(out), "w", encoding="utf-8") as handle:
        handle.write(doc)
    print(f"Wrote {os.path.normpath(out)}")


if __name__ == "__main__":
    main()
